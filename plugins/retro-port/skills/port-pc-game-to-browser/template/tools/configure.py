#!/usr/bin/env python3
"""Turns port.json (this game's settings) into the files the build reads.

    python3 -I tools/configure.py            (run by recomp/build.sh and recomp/build_web.sh)

Writes:
  recomp/host/port_config.h          names, paths, registry values and pad identity for the Windows layer
  recomp/web/port-config.js          name, executable and file rules for the page
  recomp/web/cloudflare/wrangler.toml Worker and bucket names (only the name lines are rewritten)

port.json fields (see port.example.json):
  name          display name, e.g. "Cricket 07"
  id            lower-case slug for file and storage names, e.g. "cricket07"
  exe           the executable to recompile, relative to game/ (must be unprotected)
  guest_exe     the file name the game believes it was started as (default: basename of exe)
  guest_root    the folder the game believes it is installed in (default: C:\\Games\\<id>)
  volume_label  label reported for the game's CD drive (default: id upper-cased)
  files         {"include": [path prefixes] (empty = the whole folder), "required": [paths]}
  registry      [{"key": "...", "value": "...", "sz": "text"} or {..., "dword": 123}]: values the game
                reads; take them from a real install of your own copy
  pad           {"name": "...", "vid": "046D", "pid": "C216"}: the controller the game is shown,
                ideally one its controller table already knows
  online        true to offer online 1v1 (only for games with local multiplayer)
  controls      one line of control hints for the launcher
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load():
    path = os.path.join(ROOT, "port.json")
    if not os.path.exists(path):
        raise SystemExit("port.json is missing: copy port.example.json and fill it in for your game")
    cfg = json.load(open(path))
    for k in ("name", "id", "exe"):
        if not cfg.get(k):
            raise SystemExit(f"port.json: '{k}' is required")
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", cfg["id"]):
        raise SystemExit("port.json: 'id' must be lower-case letters, digits and dashes")
    cfg.setdefault("guest_exe", os.path.basename(cfg["exe"].replace("\\", "/")))
    cfg.setdefault("guest_root", "C:\\Games\\" + cfg["id"])
    cfg.setdefault("volume_label", cfg["id"].upper().replace("-", "")[:11])
    cfg.setdefault("files", {})
    cfg["files"].setdefault("include", [])
    cfg["files"].setdefault("required", [])
    cfg.setdefault("registry", [])
    cfg.setdefault("pad", {})
    cfg["pad"].setdefault("name", "Logitech Dual Action USB")
    cfg["pad"].setdefault("vid", "046D")
    cfg["pad"].setdefault("pid", "C216")
    cfg.setdefault("online", False)
    cfg.setdefault("controls", "Use a controller or the keyboard.")
    return cfg


def write_if_changed(path, text):
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w") as f:
            f.write(text)


def main():
    cfg = load()
    vid, pid = int(cfg["pad"]["vid"], 16), int(cfg["pad"]["pid"], 16)
    reg = []
    for r in cfg["registry"]:
        if "dword" in r:
            reg.append(f'    {{ {c_str(r["key"])}, {c_str(r.get("value", ""))}, 4, NULL, {int(r["dword"])}u }},')
        else:
            reg.append(f'    {{ {c_str(r["key"])}, {c_str(r.get("value", ""))}, 1, {c_str(r.get("sz", ""))}, 0 }},')
    h = f"""/* Generated by tools/configure.py from port.json: edit port.json, not this file. */
#ifndef PORT_CONFIG_H
#define PORT_CONFIG_H
#define PORT_NAME {c_str(cfg["name"])}
#define PORT_ID {c_str(cfg["id"])}
#define PORT_EXE {c_str(cfg["exe"])}
#define PORT_GUEST_ROOT {c_str(cfg["guest_root"])}
#define PORT_GUEST_EXE {c_str(cfg["guest_exe"])}
#define PORT_VOLUME_LABEL {c_str(cfg["volume_label"])}
#define PORT_PAD_NAME {c_str(cfg["pad"]["name"])}
#define PORT_PAD_VID 0x{vid:04X}u
#define PORT_PAD_PID 0x{pid:04X}u
/* registry values the game reads (RegValue rows: key, value, type, string data, dword data) */
#define PORT_REGISTRY \\
{os.linesep.join(line + " \\" for line in reg)}
    /* end */
#endif
"""
    write_if_changed(os.path.join(ROOT, "recomp/host/port_config.h"), h)
    js = {k: cfg[k] for k in ("name", "id", "exe", "online", "controls")}
    js["files"] = cfg["files"]
    write_if_changed(os.path.join(ROOT, "recomp/web/port-config.js"),
                     "// Generated by tools/configure.py from port.json: edit port.json, not this file.\n"
                     f"window.PORT = {json.dumps(js, indent=2)};\n")
    w = os.path.join(ROOT, "recomp/web/cloudflare/wrangler.toml")
    if os.path.exists(w):
        t = open(w).read()
        t = re.sub(r'(?m)^name = ".*"$', f'name = "{cfg["id"]}-web"', t)
        t = re.sub(r'(?m)^bucket_name = ".*"$', f'bucket_name = "{cfg["id"]}-web"', t)
        write_if_changed(w, t)
    if "--print-exe" in sys.argv:
        print(cfg["exe"])


if __name__ == "__main__":
    main()
